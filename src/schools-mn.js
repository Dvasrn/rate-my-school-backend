// ── Кирилл → латин галиглал (тогтвортой, ASCII _id үүсгэх зорилготой) ────────
const TRANSLIT = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "yo", ж: "j", з: "z",
  и: "i", й: "i", к: "k", л: "l", м: "m", н: "n", о: "o", ө: "o", п: "p",
  р: "r", с: "s", т: "t", у: "u", ү: "u", ф: "f", х: "h", ц: "ts", ч: "ch",
  ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};

const slugify = (text) =>
  [...text.toLowerCase()]
    .map((ch) => TRANSLIT[ch] ?? (/[a-z0-9]/.test(ch) ? ch : "-"))
    .join("")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");

// ө→o, ү→u галиглалаас болж давхардал үүсэж болзошгүй тул -2, -3 залгана.
const makeIdFactory = () => {
  const used = new Set();
  return (raw) => {
    const base = `school-${slugify(raw)}`;
    if (!used.has(base)) {
      used.add(base);
      return base;
    }
    let n = 2;
    while (used.has(`${base}-${n}`)) n += 1;
    used.add(`${base}-${n}`);
    return `${base}-${n}`;
  };
};

