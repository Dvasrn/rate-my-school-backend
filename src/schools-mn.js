/**
 * Бүх сургуулийн жагсаалтыг үүсгэнэ.
 * @returns {Array<{_id: string, schoolName: string, location: string,
 *                  schoolType: "University"|"HighSchool"|"Collage",
 *                  isSchoolPrivate: boolean}>}
 */
export const mongolianSchools = () => {
  const nextId = makeIdFactory();
  const schools = [];

  const push = (explicitId, schoolName, location, schoolType, isSchoolPrivate) => {
    schools.push({
      _id: explicitId ?? nextId(schoolName),
      schoolName,
      location,
      schoolType,
      isSchoolPrivate,
    });
  };

  // 1. Их, дээд сургууль
  for (const u of UNIVERSITIES) {
    push(u.id, u.name, u.location, "University", u.private);
  }

  // 2. Коллеж (нийслэл)
  for (const c of COLLEGES) {
    push(c.id, c.name, c.location, "Collage", c.private);
  }

  // 3. Аймаг бүрийн политехник коллеж
  for (const aimag of AIMAGS) {
    push(
      null,
      `${aimag.name} аймгийн Политехник коллеж`,
      `${aimag.name} аймаг, ${aimag.center}`,
      "Collage",
      false
    );
  }

  // 4. Улаанбаатарын дугаартай ЕБС
  for (let n = 1; n <= UB_NUMBERED_MAX; n += 1) {
    push(
      UB_NUMBERED_ID[n],
      `Нийслэлийн ${n}-р сургууль`,
      UB_DISTRICT_OF[n] ?? "Улаанбаатар",
      "HighSchool",
      false
    );
  }

  // 5. Багануур, Багахангай, Налайх дүүргийн ЕБС
  for (const { district, count } of UB_OUTER_DISTRICTS) {
    const short = district.replace(" дүүрэг", "");
    for (let n = 1; n <= count; n += 1) {
      push(null, `${short} дүүргийн ${n}-р сургууль`, district, "HighSchool", false);
    }
  }

  // 6. Нийслэлийн нэртэй (ихэвчлэн хувийн) сургуулиуд
  for (const s of UB_NAMED_SCHOOLS) {
    push(s.id, s.name, s.location, "HighSchool", s.private);
  }

  // 7. Аймгийн төвийн дугаартай ЕБС
  for (const aimag of AIMAGS) {
    for (let n = 1; n <= aimag.centerSchools; n += 1) {
      push(
        null,
        `${aimag.name} аймгийн ${n}-р сургууль`,
        `${aimag.name} аймаг, ${aimag.center}`,
        "HighSchool",
        false
      );
    }
  }

  // 8. Сум бүрийн ЕБС (төв сумыг оруулахгүй — түүнийг 7-д дугаартайгаар нэмсэн)
  for (const aimag of AIMAGS) {
    for (const sum of aimag.sums) {
      if (sum === aimag.centerSum) continue;
      push(
        null,
        `${aimag.name} аймгийн ${sum} сумын ерөнхий боловсролын сургууль`,
        `${aimag.name} аймаг, ${sum} сум`,
        "HighSchool",
        false
      );
    }
  }

  return schools;
};
